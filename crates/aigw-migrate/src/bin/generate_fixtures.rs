//! Generate synthetic fixtures for verify_nested_decrypt tests.
//!
//! Creates realistic-shaped litellm_params JSON, encrypts with TEST_MASTER_KEY,
//! and writes the fixture JSON file.  Run this whenever the fixture file is
//! missing or needs regeneration with a different structure.
//!
//! NOTE: For **real** litellm-encrypted blobs, use `export_fixtures` instead
//! (requires access to upstream PG DB).

use aigw_core::crypto::encrypt_litellm_value;
use serde_json::json;
use std::fs;

const TEST_MASTER_KEY: &str = "sk-test-fixture-key-0000000000000000";
const OUT_PATH: &str = "tests/fixtures/encrypted_params_fixtures.json";

fn enc(v: &str) -> String {
    encrypt_litellm_value(v, TEST_MASTER_KEY).unwrap()
}

fn main() {
    // Build realistic litellm_param shapes (matching typical upstream entries).
    // Each entry mimics the JSON structure litellm stores, with some fields
    // encrypted (api_base, api_key etc.) and some plaintext (model, provider).

    let models = vec![
        // ── maas/deepseek-v4-flash ──
        (
            "maas/deepseek-v4-flash",
            json!({
                "model": "deepseek-v4-flash",
                "api_base": enc("https://api.maas.example.com/v1"),
                "api_key": enc("sk-maas-deepseek-key-12345"),
                "custom_llm_provider": "openai",
                "litellm_credential_name": "maas-deepseek-cred",
                "rpm": 1000,
                "tpm": 200000,
            }),
            Some(json!({
                "api_key": enc("sk-maas-deepseek-key-12345"),
                "api_base": enc("https://api.maas.example.com/v1"),
            })),
            Some("api.maas.example.com/v1"),
            Some("deepseek-v4-flash"),
        ),
        // ── tke/kimi-k25 ──
        (
            "tke/kimi-k25",
            json!({
                "model": "kimi-k25",
                "api_base": enc("https://api.tke.example.com/v1"),
                "api_key": enc("sk-tke-kimi-key-67890"),
                "custom_llm_provider": "openai",
                "litellm_credential_name": "tke-kimi-cred",
                "rpm": 500,
                "tpm": 100000,
            }),
            Some(json!({
                "api_key": enc("sk-tke-kimi-key-67890"),
                "api_base": enc("https://api.tke.example.com/v1"),
            })),
            Some("api.tke.example.com/v1"),
            Some("kimi-k25"),
        ),
        // ── model WITHOUT credential reference ──
        (
            "direct/model-no-cred",
            json!({
                "model": "direct-model",
                "api_base": enc("https://api.direct.example.com/v1"),
                "api_key": enc("sk-direct-key-abc"),
                "custom_llm_provider": "openai",
                "rpm": 3000,
            }),
            None,
            Some("api.direct.example.com/v1"),
            Some("direct-model"),
        ),
    ];

    let fixtures: Vec<serde_json::Value> = models
        .into_iter()
        .map(|(name, params, cred, api_base, model)| {
            let params_str = serde_json::to_string(&params).unwrap();
            let encrypted_params = enc(&params_str);

            let enc_cred = cred.map(|c| {
                let cred_str = serde_json::to_string(&c).unwrap();
                enc(&cred_str)
            });

            json!({
                "model_name": name,
                "encrypted_litellm_params": encrypted_params,
                "encrypted_credential_values": enc_cred,
                "expected_api_base_suffix": api_base,
                "expected_model": model,
            })
        })
        .collect();

    let output = serde_json::json!({
        "_note": "SYNTHETIC fixtures (generated by generate_fixtures). Run export_fixtures to replace with real litellm-encrypted blobs.",
        "description": "Encrypted litellm_params fixtures for verify_nested_decrypt tests. Re-encrypted with TEST_MASTER_KEY so no real secrets are exposed.",
        "test_key": TEST_MASTER_KEY,
        "models": fixtures,
    });

    fs::create_dir_all("tests/fixtures").unwrap();
    fs::write(OUT_PATH, serde_json::to_string_pretty(&output).unwrap()).unwrap();
    println!("Fixture written to {}", OUT_PATH);
}
